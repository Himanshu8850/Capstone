-- BookyGeek V1 schema (approved data model, gate G-DM, 2026-11-12). 11 tables.
-- Conventions: BIGINT identity primary keys, TIMESTAMPTZ in UTC, money NUMERIC(12,2) (book price NUMERIC(10,2)).
-- Not modelled by design: coupon, wallet, wishlist, review/rating, author profile, genre, brand, role, shipment, admin.
-- Payment secrets (PAN, CVV, expiry, name on card, UPI id) are never stored: there is no column for them.

-- ============================================================================================================
-- Part 1: identity tables (User & Authentication, Reward Points)
-- ============================================================================================================

CREATE TABLE customer (
    id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL CHECK (btrim(full_name) <> ''),
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    token_version INTEGER      NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL,
    -- Stored trimmed and lower-cased by the application; the UNIQUE index makes e-mail unique case-insensitively.
    CONSTRAINT uq_customer_email UNIQUE (email)
);

CREATE TABLE address (
    id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id   BIGINT       NOT NULL REFERENCES customer (id) ON DELETE CASCADE,
    full_name     VARCHAR(100) NOT NULL,
    phone         CHAR(10)     NOT NULL CHECK (phone ~ '^[0-9]{10}$'),
    address_line1 VARCHAR(150) NOT NULL,
    address_line2 VARCHAR(150) NULL,
    city          VARCHAR(80)  NOT NULL,
    state         VARCHAR(60)  NOT NULL,
    pin_code      CHAR(6)      NOT NULL CHECK (pin_code ~ '^[0-9]{6}$'),
    country       VARCHAR(56)  NOT NULL DEFAULT 'India',
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_address_customer ON address (customer_id);

CREATE TABLE reward_account (
    customer_id BIGINT  NOT NULL PRIMARY KEY REFERENCES customer (id) ON DELETE CASCADE,
    balance     INTEGER NOT NULL CHECK (balance >= 0)
);

-- Movements only (there is no "earn" type). order_id references orders; that foreign key is added in part 3 because
-- orders is created later in this script.
CREATE TABLE reward_transaction (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id BIGINT      NOT NULL REFERENCES customer (id),
    order_id    BIGINT      NOT NULL,
    type        VARCHAR(10) NOT NULL CHECK (type IN ('REDEEM', 'RESTORE')),
    points      INTEGER     NOT NULL CHECK (points > 0),
    created_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_reward_transaction_order_type UNIQUE (order_id, type)
);
CREATE INDEX idx_reward_transaction_customer ON reward_transaction (customer_id);

-- ============================================================================================================
-- Part 2: catalogue tables (Category & Brand, Book Catalogue)
-- ============================================================================================================

CREATE TABLE category (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(80) NOT NULL,
    parent_id  BIGINT      NULL REFERENCES category (id),
    sort_order INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT uq_category_name UNIQUE (name),
    CONSTRAINT ck_category_not_own_parent CHECK (parent_id <> id)
);
CREATE INDEX idx_category_parent ON category (parent_id);

-- publisher is the brand (no brand table). Unavailable = a physical book with stock_quantity = 0.
CREATE TABLE book (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200)  NOT NULL,
    author          VARCHAR(120)  NOT NULL,
    description     TEXT          NOT NULL,
    publisher       VARCHAR(120)  NOT NULL,
    format          VARCHAR(10)   NOT NULL CHECK (format IN ('PAPERBACK', 'HARDCOVER', 'EBOOK')),
    language        VARCHAR(40)   NOT NULL,
    price           NUMERIC(10,2) NOT NULL CHECK (price > 0),
    stock_quantity  INTEGER       NULL,
    front_cover_url VARCHAR(255)  NOT NULL,
    back_cover_url  VARCHAR(255)  NULL,
    listed          BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_book_stock CHECK (
        (format = 'EBOOK' AND stock_quantity IS NULL)
        OR (format <> 'EBOOK' AND stock_quantity IS NOT NULL AND stock_quantity >= 0))
);
CREATE INDEX idx_book_publisher ON book (publisher);
CREATE INDEX idx_book_language  ON book (language);
CREATE INDEX idx_book_format    ON book (format);
CREATE INDEX idx_book_price     ON book (price);
CREATE INDEX idx_book_listed    ON book (listed);

CREATE TABLE book_category (
    book_id     BIGINT NOT NULL REFERENCES book (id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES category (id),
    PRIMARY KEY (book_id, category_id)
);
CREATE INDEX idx_book_category_category ON book_category (category_id);

-- ============================================================================================================
-- Part 3: basket, order and payment tables (Shopping Cart, Order Management, Payment Management)
-- ============================================================================================================

-- A basket is simply the set of a customer's items (no header table). Price is never stored: the live price is used.
CREATE TABLE basket_item (
    customer_id BIGINT      NOT NULL REFERENCES customer (id) ON DELETE CASCADE,
    book_id     BIGINT      NOT NULL REFERENCES book (id),
    quantity    INTEGER     NOT NULL CHECK (quantity BETWEEN 1 AND 10),
    updated_at  TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (customer_id, book_id)
);

-- "orders" because ORDER is a reserved word. The display reference BG-<zero-padded id> is derived, not stored.
CREATE TABLE orders (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id     BIGINT        NOT NULL REFERENCES customer (id),
    status          VARCHAR(10)   NOT NULL CHECK (status IN ('PLACED', 'CANCELLED')),
    placed_at       TIMESTAMPTZ   NOT NULL,
    cancelled_at    TIMESTAMPTZ   NULL,
    -- Address snapshot: later edits or deletes of a saved address must not alter order history.
    ship_full_name  VARCHAR(100)  NOT NULL,
    ship_phone      CHAR(10)      NOT NULL CHECK (ship_phone ~ '^[0-9]{10}$'),
    ship_line1      VARCHAR(150)  NOT NULL,
    ship_line2      VARCHAR(150)  NULL,
    ship_city       VARCHAR(80)   NOT NULL,
    ship_state      VARCHAR(60)   NOT NULL,
    ship_pin_code   CHAR(6)       NOT NULL CHECK (ship_pin_code ~ '^[0-9]{6}$'),
    ship_country    VARCHAR(56)   NOT NULL,
    subtotal        NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    tax             NUMERIC(12,2) NOT NULL CHECK (tax >= 0),
    delivery_charge NUMERIC(12,2) NOT NULL CHECK (delivery_charge >= 0),
    points_redeemed INTEGER       NOT NULL DEFAULT 0 CHECK (points_redeemed >= 0),
    payable_total   NUMERIC(12,2) NOT NULL,
    CONSTRAINT ck_orders_cancelled_at CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL)),
    -- Database backstop for the approved 50% reward cap (1 point = Rs 1): 2 * points <= subtotal + tax + delivery.
    CONSTRAINT ck_orders_reward_cap CHECK (2 * points_redeemed <= subtotal + tax + delivery_charge),
    CONSTRAINT ck_orders_payable_total CHECK (
        payable_total = subtotal + tax + delivery_charge - points_redeemed AND payable_total > 0)
);
CREATE INDEX idx_orders_customer_placed ON orders (customer_id, placed_at DESC);

ALTER TABLE reward_transaction
    ADD CONSTRAINT fk_reward_transaction_order FOREIGN KEY (order_id) REFERENCES orders (id);

CREATE TABLE order_item (
    order_id   BIGINT        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    book_id    BIGINT        NOT NULL REFERENCES book (id),
    quantity   INTEGER       NOT NULL CHECK (quantity BETWEEN 1 AND 10),
    -- Price snapshot taken at placement.
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price > 0),
    PRIMARY KEY (order_id, book_id)
);

-- One row per payment attempt. A declined attempt is FAILED with no order.
CREATE TABLE payment (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id     BIGINT        NOT NULL REFERENCES customer (id),
    order_id        BIGINT        NULL REFERENCES orders (id),
    method          VARCHAR(12)   NOT NULL CHECK (method IN ('CREDIT_CARD', 'DEBIT_CARD', 'UPI', 'COD')),
    status          VARCHAR(22)   NOT NULL
                    CHECK (status IN ('PAID', 'PENDING_ON_DELIVERY', 'FAILED', 'REFUNDED', 'CANCELLED')),
    amount          NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    failure_code    VARCHAR(40)   NULL,
    idempotency_key UUID          NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_payment_order UNIQUE (order_id),
    CONSTRAINT uq_payment_customer_idempotency UNIQUE (customer_id, idempotency_key),
    CONSTRAINT ck_payment_order_link CHECK (
        (status = 'FAILED' AND order_id IS NULL) OR (status <> 'FAILED' AND order_id IS NOT NULL))
);
